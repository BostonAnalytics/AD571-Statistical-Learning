import pandas as pd
import seaborn as sns
import statsmodels.formula.api as smf
import matplotlib.pyplot as plt

boston = pd.read_csv("../datasets/Boston.csv")

print(boston.info())
print(boston.describe())

sns.regplot(data=boston, x="lstat", y="medv", scatter_kws={"alpha": 0.65})
plt.xlabel("Percent lower status population")
plt.ylabel("Median home value")
plt.title("A simple baseline relationship")
plt.show()

baseline = smf.ols("medv ~ lstat", data=boston).fit()
expanded = smf.ols("medv ~ lstat + rm + ptratio + crim", data=boston).fit()

print(baseline.summary())
print(expanded.summary())
