from sklearn.model_selection import train_test_split
from sklearn.metrics import mean_squared_error, r2_score

train, test = train_test_split(boston, train_size=0.8, random_state=571)

fit = smf.ols("medv ~ lstat + rm + ptratio + crim", data=train).fit()
pred = fit.predict(test)

rmse = mean_squared_error(test["medv"], pred) ** 0.5
test_r2 = r2_score(test["medv"], pred)

print({"rmse": rmse, "test_r2": test_r2})
