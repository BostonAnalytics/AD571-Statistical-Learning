set.seed(571)

id <- sample(seq_len(nrow(boston)), size = 0.8 * nrow(boston))
train <- boston[id, ]
test <- boston[-id, ]

fit <- lm(medv ~ lstat + rm + ptratio + crim, data = train)
pred <- predict(fit, newdata = test)

rmse <- sqrt(mean((test$medv - pred)^2))
test_r2 <- 1 - sum((test$medv - pred)^2) /
  sum((test$medv - mean(test$medv))^2)

c(rmse = rmse, test_r2 = test_r2)
